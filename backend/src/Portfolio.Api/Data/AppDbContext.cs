using Microsoft.EntityFrameworkCore;
using Portfolio.Api.Entities;

namespace Portfolio.Api.Data;

public class AppDbContext(DbContextOptions<AppDbContext> options) : DbContext(options)
{
    public DbSet<Project> Projects => Set<Project>();
    public DbSet<Profile> Profiles => Set<Profile>();
    public DbSet<SkillGroup> SkillGroups => Set<SkillGroup>();
    public DbSet<Experience> Experiences => Set<Experience>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<Project>(e =>
        {
            e.Property(p => p.Slug).HasMaxLength(100);
            e.HasIndex(p => p.Slug).IsUnique();
            e.Property(p => p.RepoUrl).HasMaxLength(500);
            e.Property(p => p.LiveUrl).HasMaxLength(500);
            e.Property(p => p.CoverImage).HasMaxLength(500);

            // One project → many translations; deleting a project deletes its translations.
            e.HasMany(p => p.Translations)
                .WithOne()
                .HasForeignKey(t => t.ProjectId)
                .OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<ProjectTranslation>(e =>
        {
            e.ToTable("ProjectTranslations");
            e.HasKey(t => new { t.ProjectId, t.Language });
            e.Property(t => t.Language).HasMaxLength(5);
            e.Property(t => t.Title).HasMaxLength(200);
            e.Property(t => t.Summary).HasMaxLength(500);
            // Content has no max length: "text" column in PostgreSQL.
        });

        // Smaller content: translated texts and lists are stored as JSON columns, not in separate tables.
        modelBuilder.Entity<Profile>(e =>
        {
            // Single row with a fixed Id (1): not generated by the database.
            e.Property(p => p.Id).ValueGeneratedNever();
            e.Property(p => p.Name).HasMaxLength(100);
            e.Property(p => p.Email).HasMaxLength(200);
            e.Property(p => p.Role).HasJsonConversion();
            e.Property(p => p.Bio).HasJsonConversion();
            e.Property(p => p.Location).HasJsonConversion();
            e.Property(p => p.Links).HasJsonConversion();
        });

        modelBuilder.Entity<SkillGroup>(e =>
        {
            e.Property(g => g.Name).HasMaxLength(50);
            e.Property(g => g.Description).HasJsonConversion();
            e.Property(g => g.Skills).HasJsonConversion();
        });

        modelBuilder.Entity<Experience>(e =>
        {
            e.Property(x => x.Start).HasMaxLength(7);
            e.Property(x => x.End).HasMaxLength(7);
            e.Property(x => x.Company).HasMaxLength(100);
            e.Property(x => x.Role).HasJsonConversion();
            e.Property(x => x.Location).HasJsonConversion();
            e.Property(x => x.Description).HasJsonConversion();
            e.Property(x => x.Tags).HasJsonConversion();
        });
    }
}
